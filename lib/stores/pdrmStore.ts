// "Important-only" heuristics
export function isHighlightImportant(text: string): boolean {
  // Skip very short text (likely accidental)
  if (text.length < 15) return false;
  
  // Skip common/generic words only
  const genericPatterns = [
    /^(the|a|an|this|that|these|those|is|are|was|were|be|been|being)\s*$/i,
    /^\d+\.?\s*$/,  // Just numbers
    /^[\s\W]+$/,    // Just whitespace/punctuation
  ];
  
  if (genericPatterns.some(p => p.test(text))) return false;
  
  // Check for high-signal indicators
  const importantIndicators = [
    /\b(key|important|critical|essential|remember|note|caution|warning)\b/i,
    /\b(principle|concept|definition|formula|rule|law)\b/i,
    /\b(treatment|diagnosis|symptom|sign|cause|effect|mechanism)\b/i,
    /\d+%/,  // Percentages
    /\b\d+\s*(mg|ml|g|kg|mmHg|cm|mm)\b/i,  // Medical values
    /\b(first|second|third|always|never|must|should)\b/i,
  ];
  
  const hasImportantIndicator = importantIndicators.some(p => p.test(text));
  
  // Text with numbers/values is often important
  const hasNumbers = /\d/.test(text);
  
  // Multiple words suggests meaningful content
  const wordCount = text.split(/\s+/).length;
  const isMeaningfulLength = wordCount >= 3 && wordCount <= 100;
  
  return (hasImportantIndicator || hasNumbers) && isMeaningfulLength;
}

// Generate compact summary
export function generateCompactSummary(text: string, maxLength: number = 200): string {
  // Clean up text
  const cleaned = text
    .replace(/\s+/g, ' ')
    .replace(/\n+/g, ' ')
    .trim();
  
  if (cleaned.length <= maxLength) return cleaned;
  
  // Try to break at sentence boundary
  const sentences = cleaned.match(/[^.!?]+[.!?]+/g) || [cleaned];
  let result = '';
  
  for (const sentence of sentences) {
    if ((result + sentence).length <= maxLength) {
      result += sentence;
    } else {
      break;
    }
  }
  
  if (!result) {
    // No complete sentence fits, truncate with ellipsis
    result = cleaned.substring(0, maxLength - 3) + '...';
  }
  
  return result.trim();
}

// Extract key points from text
export function extractKeyPoints(text: string, maxPoints: number = 3): string[] {
  const points: string[] = [];
  
  // Look for numbered lists
  const numberedItems = text.match(/\d+[.)]\s*[^.!?\n]+[.!?]?/g);
  if (numberedItems) {
    points.push(...numberedItems.slice(0, maxPoints).map(s => s.trim()));
  }
  
  // Look for key phrases
  if (points.length < maxPoints) {
    const keyPhrases = [
      /\b(is defined as|refers to|means)\s+([^.!?]+[.!?])/gi,
      /\b(characterized by|consists of)\s+([^.!?]+[.!?])/gi,
      /\b(treatment|management|approach)\s+(is|includes?)\s+([^.!?]+[.!?])/gi,
    ];
    
    for (const pattern of keyPhrases) {
      const matches = text.matchAll(pattern);
      for (const match of matches) {
        if (points.length >= maxPoints) break;
        const phrase = match[0].trim();
        if (phrase.length > 10 && !points.includes(phrase)) {
          points.push(phrase);
        }
      }
    }
  }
  
  // Fallback: first meaningful sentences
  if (points.length < maxPoints) {
    const sentences = text.match(/[^.!?]+[.!?]+/g) || [];
    for (const sentence of sentences) {
      if (points.length >= maxPoints) break;
      const trimmed = sentence.trim();
      if (trimmed.length > 20 && !points.includes(trimmed)) {
        points.push(trimmed);
      }
    }
  }
  
  return points.slice(0, maxPoints);
}

// Get classification color
export function getPdrmColor(classification: PDRMClassification): string {
  switch (classification) {
    case 'pattern': return '#8b5cf6';   // Purple
    case 'decision': return '#3b82f6';  // Blue
    case 'risk': return '#ef4444';      // Red
    case 'mnemonic': return '#f59e0b';  // Orange/Yellow
    case 'general': return '#6b7280';   // Gray
    default: return '#6b7280';
  }
}

// Get classification icon
export function getPdrmIcon(classification: PDRMClassification): string {
  switch (classification) {
    case 'pattern': return '🔷';
    case 'decision': return '⚖️';
    case 'risk': return '⚠️';
    case 'mnemonic': return '💡';
    case 'general': return '📝';
    default: return '📝';
  }
}

// Get classification label
export function getPdrmLabel(classification: PDRMClassification): string {
  switch (classification) {
    case 'pattern': return 'Pattern';
    case 'decision': return 'Decision Rule';
    case 'risk': return 'Risk/Mistake';
    case 'mnemonic': return 'Mnemonic';
    case 'general': return 'General';
    default: return 'General';
  }
}
