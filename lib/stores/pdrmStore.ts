// lib/stores/pdrmStore.ts
// PDRM Store - Manages Pattern/Decision/Risk/Mnemonic entries
// Linked to highlights with page-level grouping

import { create } from 'zustand';
import { persist, createJSONStorage } from 'zustand/middleware';

// ============================================================================
// Types
// ============================================================================

export type PDRMClassification = 'pattern' | 'decision' | 'risk' | 'mnemonic' | 'general';

export interface PDRMSource {
  documentId: string;
  documentName?: string;
  pageNumber: number;
  chapterTitle?: string;
  highlightId: string;
  quote: string;  // Original highlighted text
}

export interface PDRMEntry {
  id: string;
  classification: PDRMClassification;
  source: PDRMSource;
  
  // Condensed summary (important-only)
  summary: string;  // 1-3 bullet points or single compact line
  keyPoints: string[];  // Extracted key facts
  
  // Confidence and metadata
  confidence: number;  // 0-1
  isAutoGenerated: boolean;
  isImportant: boolean;  // Whether this passed "important-only" filter
  
  // Timestamps
  createdAt: string;
  updatedAt: string;
}

export interface PDRMDocument {
  documentId: string;
  documentName: string;
  entries: PDRMEntry[];
  lastUpdated: string;
}

interface PDRMState {
  // Data
  documents: Record<string, PDRMDocument>;  // documentId -> document
  autoMode: boolean;  // Auto vs Manual classification mode
  
  // Active context
  activeDocumentId: string | null;
  
  // Actions
  setAutoMode: (enabled: boolean) => void;
  setActiveDocument: (documentId: string) => void;
  
  // CRUD
  addEntry: (entry: Omit<PDRMEntry, 'id' | 'createdAt' | 'updatedAt'>) => string;
  updateEntry: (id: string, updates: Partial<PDRMEntry>) => void;
  deleteEntry: (id: string) => void;
  
  // Queries
  getEntriesByDocument: (documentId: string) => PDRMEntry[];
  getEntriesByPage: (documentId: string, pageNumber: number) => PDRMEntry[];
  getEntriesByClassification: (documentId: string, classification: PDRMClassification) => PDRMEntry[];
  getEntryByHighlightId: (highlightId: string) => PDRMEntry | undefined;
  
  // Grouping for PDRM Tab
  getEntriesGroupedByChapter: (documentId: string) => Record<string, PDRMEntry[]>;
  getEntriesGroupedByPage: (documentId: string) => Record<number, PDRMEntry[]>;
  
  // Stats
  getStats: (documentId: string) => {
    total: number;
    byClassification: Record<PDRMClassification, number>;
    important: number;
  };
}

// ============================================================================
// Helper Functions
// ============================================================================

function generateId(): string {
  return `pdrm_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`;
}

function now(): string {
  return new Date().toISOString();
}

// ============================================================================
// Store
// ============================================================================

export const usePdrmStore = create<PDRMState>()(
  persist(
    (set, get) => ({
      documents: {},
      autoMode: true,
      activeDocumentId: null,
      
      setAutoMode: (enabled) => {
        set({ autoMode: enabled });
      },
      
      setActiveDocument: (documentId) => {
        set({ activeDocumentId: documentId });
      },
      
      addEntry: (entryData) => {
        const id = generateId();
        const timestamp = now();
        
        const entry: PDRMEntry = {
          ...entryData,
          id,
          createdAt: timestamp,
          updatedAt: timestamp
        };
        
        set((state) => {
          const docId = entry.source.documentId;
          const existingDoc = state.documents[docId];
          
          const updatedDoc: PDRMDocument = existingDoc 
            ? {
                ...existingDoc,
                entries: [...existingDoc.entries, entry],
                lastUpdated: timestamp
              }
            : {
                documentId: docId,
                documentName: entry.source.documentName || docId,
                entries: [entry],
                lastUpdated: timestamp
              };
          
          return {
            documents: {
              ...state.documents,
              [docId]: updatedDoc
            }
          };
        });
        
        return id;
      },
      
      updateEntry: (id, updates) => {
        set((state) => {
          const newDocuments = { ...state.documents };
          
          for (const docId of Object.keys(newDocuments)) {
            const doc = newDocuments[docId];
            const entryIndex = doc.entries.findIndex(e => e.id === id);
            
            if (entryIndex !== -1) {
              const updatedEntries = [...doc.entries];
              updatedEntries[entryIndex] = {
                ...updatedEntries[entryIndex],
                ...updates,
                updatedAt: now()
              };
              
              newDocuments[docId] = {
                ...doc,
                entries: updatedEntries,
                lastUpdated: now()
              };
              break;
            }
          }
          
          return { documents: newDocuments };
        });
      },
      
      deleteEntry: (id) => {
        set((state) => {
          const newDocuments = { ...state.documents };
          
          for (const docId of Object.keys(newDocuments)) {
            const doc = newDocuments[docId];
            const filteredEntries = doc.entries.filter(e => e.id !== id);
            
            if (filteredEntries.length !== doc.entries.length) {
              newDocuments[docId] = {
                ...doc,
                entries: filteredEntries,
                lastUpdated: now()
              };
              break;
            }
          }
          
          return { documents: newDocuments };
        });
      },
      
      getEntriesByDocument: (documentId) => {
        const doc = get().documents[documentId];
        return doc?.entries || [];
      },
      
      getEntriesByPage: (documentId, pageNumber) => {
        const entries = get().getEntriesByDocument(documentId);
        return entries.filter(e => e.source.pageNumber === pageNumber);
      },
      
      getEntriesByClassification: (documentId, classification) => {
        const entries = get().getEntriesByDocument(documentId);
        return entries.filter(e => e.classification === classification);
      },
      
      getEntryByHighlightId: (highlightId) => {
        const { documents } = get();
        for (const doc of Object.values(documents)) {
          const entry = doc.entries.find(e => e.source.highlightId === highlightId);
          if (entry) return entry;
        }
        return undefined;
      },
      
      getEntriesGroupedByChapter: (documentId) => {
        const entries = get().getEntriesByDocument(documentId);
        const grouped: Record<string, PDRMEntry[]> = {};
        
        for (const entry of entries) {
          const chapter = entry.source.chapterTitle || 'Unknown Chapter';
          if (!grouped[chapter]) grouped[chapter] = [];
          grouped[chapter].push(entry);
        }
        
        return grouped;
      },
      
      getEntriesGroupedByPage: (documentId) => {
        const entries = get().getEntriesByDocument(documentId);
        const grouped: Record<number, PDRMEntry[]> = {};
        
        for (const entry of entries) {
          const page = entry.source.pageNumber;
          if (!grouped[page]) grouped[page] = [];
          grouped[page].push(entry);
        }
        
        return grouped;
      },
      
      getStats: (documentId) => {
        const entries = get().getEntriesByDocument(documentId);
        
        const byClassification: Record<PDRMClassification, number> = {
          pattern: 0,
          decision: 0,
          risk: 0,
          mnemonic: 0,
          general: 0
        };
        
        let important = 0;
        
        for (const entry of entries) {
          byClassification[entry.classification]++;
          if (entry.isImportant) important++;
        }
        
        return {
          total: entries.length,
          byClassification,
          important
        };
      }
    }),
    {
      name: 'pdrm-storage',
      storage: createJSONStorage(() => localStorage)
    }
  )
);

